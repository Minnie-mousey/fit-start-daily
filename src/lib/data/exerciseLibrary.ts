type ExerciseSeed = {
  id: string;
  name: string;
  category: ExerciseCategory;
  activity: ExerciseActivity;
  muscles: string[];
  summary: string;
  steps: string[];
  target: ExerciseTarget;
  setup?: string;
  safety: string;
  easier: string;
  harder: string;
  alternatives: string[];
  difficulty?: Difficulty;
  demonstration?: boolean;
};

function makeExercise(seed: ExerciseSeed): Exercise {
  const setup = seed.setup?.toLowerCase() ?? "";
  const equipment = setup.includes("stair")
    ? ["stairs"]
    : setup.includes("chair")
      ? ["chair"]
      : setup.includes("wall") || setup.includes("counter") || setup.includes("rail")
        ? ["support"]
        : ["none"];
  return {
    id: seed.id,
    name: seed.name,
    category: seed.category,
    activity: seed.activity,
    difficulty: seed.difficulty ?? "beginner",
    muscles: seed.muscles,
    targetAreas: seed.muscles,
    equipment,
    setupRequirements: seed.setup ? [seed.setup] : [],
    summary: seed.summary,
    steps: seed.steps,
    tips: [seed.safety],
    safetyNotes: [seed.safety],
    easier: seed.easier,
    harder: seed.harder,
    modifications: [seed.easier, seed.harder],
    alternatives: seed.alternatives,
    source: ACTIVITY_SOURCES[seed.activity],
    ...(seed.demonstration ? { demonstration: NHS_VIDEO_GUIDE } : {}),
    target: seed.target,
  };
}

